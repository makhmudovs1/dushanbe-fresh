export function translate(locale: Locale, text: string): string {
  return locale === "tg" ? (tajik[text] ?? mobileTajik[text] ?? text) : text;
}
export function localizedName(
  locale: Locale,
  entity: { name: string; nameTj?: string | null },
) {
  return locale === "tg" && entity.nameTj?.trim() ? entity.nameTj : entity.name;
}
export function localizedDescription(
  locale: Locale,
  entity: { description: string | null; descriptionTj?: string | null },
) {
  return locale === "tg"
    ? entity.descriptionTj || entity.description
    : entity.description;
}
export function unitLabel(locale: Locale, unit: string) {
  return (
    (
      {
        kg: "кг",
        g: "г",
        piece: locale === "tg" ? "дона" : "шт.",
        pack: locale === "tg" ? "баста" : "уп.",
        bunch: locale === "tg" ? "бандча" : "пучок",
      } as Record<string, string>
    )[unit] ?? unit
  );
}
export function slotLabel(
  locale: Locale,
  slot: { date?: string; startsAt: string; endsAt: string },
) {
  const language = locale === "tg" ? "tg-TJ" : "ru-RU";
  const format = (value: string, options: Intl.DateTimeFormatOptions) =>
    new Intl.DateTimeFormat(language, {
      timeZone: "Asia/Dushanbe",
      ...options,
    }).format(new Date(value));
  if (
    /^([01]\d|2[0-3]):[0-5]\d$/.test(slot.startsAt) &&
    /^([01]\d|2[0-3]):[0-5]\d$/.test(slot.endsAt) &&
    slot.date &&
    /^\d{4}-\d{2}-\d{2}$/.test(slot.date)
  )
    return `${format(`${slot.date}T12:00:00+05:00`, { day: "numeric", month: "short" })} · ${slot.startsAt}–${slot.endsAt}`;
  return `${format(slot.startsAt, { day: "numeric", month: "short" })} · ${format(slot.startsAt, { hour: "2-digit", minute: "2-digit" })}–${format(slot.endsAt, { hour: "2-digit", minute: "2-digit" })}`;
}

// The same dynamic server messages as WEB, using the DTO's Tajik product name.
export function serverMessage(
  locale: Locale,
  message: string,
  entity?: { name: string; nameTj?: string | null },
): string {
  if (locale === "ru") return message;
  const translated = translate(locale, message);
  if (translated !== message) return translated;
  let match: RegExpMatchArray | null;
  if (
    (match = message.match(/^До минимального заказа не хватает (.+) сомони\.$/))
  )
    return `То фармоиши ҳадди ақал ${match[1]} сомонӣ намерасад.`;
  if (
    (match = message.match(/^Проверьте количество: минимум (.+), шаг (.+)\.$/))
  )
    return `Миқдорро санҷед: ҳадди ақал ${match[1]}, қадам ${match[2]}.`;
  if (/сегодня больше недоступны\.$/.test(message) && entity)
    return `${localizedName(locale, entity)} имрӯз дигар дастрас нест.`;
  if (
    (match = message.match(
      /^Цена «(.+)» изменилась с (.+) до (.+) сомони за единицу\.$/,
    )) &&
    entity
  )
    return `Нархи «${localizedName(locale, entity)}» аз ${match[2]} ба ${match[3]} сомонӣ барои воҳид тағйир ёфт.`;
  return translate(locale, "Проверьте состав, количество и условия доставки.");
}
