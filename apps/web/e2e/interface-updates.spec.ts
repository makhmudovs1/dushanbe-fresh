import { expect, test } from "@playwright/test";

test.skip(process.env.RUN_INTERFACE_UI !== "1", "Requires the existing read-only local catalog preview.");
test.beforeEach(async ({ page, baseURL }) => {
  expect(new URL(baseURL!).hostname).toBe("localhost");
  await page.route("**/api/v1/customer-auth/status", route => route.fulfill({ json: { enabled: false, requiredForCheckout: false } }));
});

for (const width of [375, 390, 430, 768]) {
  test(`mobile journey and screenshots ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 844 });
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("console", message => { if (/hydration|did not match/i.test(message.text())) errors.push(message.text()); });
    await page.goto("/");
    await expect(page.locator(".product-card").first()).toBeVisible();
    expect(await page.locator(".product-card").first().evaluate(el => el.getBoundingClientRect().top)).toBeLessThan(700);
    await expect(page.locator(".site-header .cart-link")).toBeHidden();
    await expect(page.locator(".mobile-navigation a")).toHaveCount(4);
    await page.screenshot({ path: info.outputPath(`home-${width}.png`) });
    await page.getByRole("button", { name: "Язык / Забон", exact: true }).click();
    await page.getByRole("button", { name: "Тоҷикӣ", exact: true }).click();
    await expect(page.locator("html")).toHaveAttribute("lang", "tg");
    await page.screenshot({ path: info.outputPath(`home-tj-${width}.png`) });
    await page.getByRole("button", { name: "Язык / Забон", exact: true }).click();
    await page.getByRole("button", { name: "Русский", exact: true }).click();
    await page.locator(".header-location--mobile").click();
    const address = page.getByRole("dialog", { name: "Адрес доставки", exact: true });
    await expect(address.getByText("Поиск по городу пока недоступен", { exact: true })).toBeVisible();
    await expect(address.getByLabel("Улица", { exact: true })).toHaveCount(0);
    await page.screenshot({ path: info.outputPath(`address-${width}.png`), animations: "disabled" });
    await address.getByTestId("address-manual").click();
    await address.getByLabel("Улица", { exact: true }).fill("Рудаки");
    await address.getByLabel("Дом", { exact: true }).fill("15");
    await address.getByTestId("address-next").click();
    await page.screenshot({ path: info.outputPath(`address-details-${width}.png`), animations: "disabled" });
    await address.getByTestId("address-confirm").click();
    await expect(page.locator(".header-location--mobile")).toContainText("Рудаки, 15");
    await page.locator(".mobile-navigation").getByRole("link", { name: "Каталог", exact: true }).click();
    await page.screenshot({ path: info.outputPath(`categories-${width}.png`) });
    await page.goto("/catalog?category=vegetables");
    const product = page.locator(".product-card").first();
    const name = (await product.locator("h3").innerText()).trim();
    await expect(product.locator(".favorite-button")).toBeHidden();
    await product.locator("h3 a").click();
    const sheet = page.getByRole("dialog", { name, exact: true });
    await expect(sheet).toBeVisible();
    await expect(page).toHaveURL(/\/catalog\?category=vegetables$/);
    await sheet.getByRole("button", { name: "В корзину", exact: true }).click();
    await expect(sheet.locator(".quantity-stepper")).toBeVisible();
    await sheet.getByRole("button", { name: `Увеличить количество: ${name}`, exact: true }).click();
    await sheet.getByRole("button", { name: new RegExp("Добавить в избранное") }).click();
    await page.screenshot({ path: info.outputPath(`product-${width}.png`) });
    await page.goBack();
    await expect(sheet).toHaveCount(0);
    await expect(product.locator(".quantity-stepper")).toBeVisible();
    await page.evaluate(() => window.scrollTo(0, 750));
    await expect(page.locator(".site-header")).toHaveClass(/site-header--compact/);
    await expect(page.getByRole("button", { name: "Наверх", exact: true })).toBeVisible();
    await page.screenshot({ path: info.outputPath(`scrolled-${width}.png`) });
    await page.getByRole("button", { name: "Наверх", exact: true }).click();
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0);
    await page.locator('.mobile-navigation a[href="/cart"]').click();
    await expect(page.locator(".cart-item")).toHaveCount(1);
    await expect(page.locator(".site-header")).toBeHidden();
    await expect(page.getByRole("heading", { name: "Подобрали для вас", exact: true })).toBeVisible();
    await page.screenshot({ path: info.outputPath(`cart-${width}.png`) });
    await page.locator(".cart-item h3 a").click();
    await expect(sheet).toBeVisible();
    await sheet.getByRole("button", { name: "Закрыть товар", exact: true }).first().click();
    await expect(sheet).toHaveCount(0);
    await page.getByRole("button", { name: "Очистить корзину", exact: true }).click();
    await page.getByRole("dialog", { name: "Очистить корзину?", exact: true }).getByRole("button", { name: "Отмена", exact: true }).last().click();
    await expect(page.locator(".cart-item")).toHaveCount(1);
    await page.getByRole("link", { name: "Оформить заказ", exact: true }).click();
    await expect(page.getByLabel("Улица", { exact: true })).toHaveValue("Рудаки");
    await expect(page.getByLabel("Дом", { exact: true })).toHaveValue("15");
    await expect(page.locator(".mobile-navigation")).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.goto("/catalog?focusSearch=1");
    await expect(page.getByRole("textbox", { name: "Поиск товаров", exact: true })).toBeFocused();
    await page.getByRole("textbox", { name: "Поиск товаров", exact: true }).fill("морковь");
    await expect(page).toHaveURL(/search=/);
    await expect(page.locator(".product-card")).toHaveCount(1);
    await page.getByRole("textbox", { name: "Поиск товаров", exact: true }).blur();
    await page.screenshot({ path: info.outputPath(`search-${width}.png`) });
    expect(errors).toEqual([]);
  });
}

