test("manual map pin moves, persists into checkout and sheet dismisses by swipe", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/catalog?category=vegetables");
  await page.locator(".header-location--mobile").click();
  const address = page.getByRole("dialog", { name: "Адрес доставки", exact: true });
  await address.getByTestId("address-choose-map").click();
  const map = address;
  await expect(map.locator(".leaflet-control-zoom")).toBeVisible();
  await map.getByRole("button", { name: "Выбрать центр карты", exact: true }).click();
  const marker = map.locator(".leaflet-marker-icon");
  await expect(marker).toBeVisible();
  const box = (await marker.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + 50, box.y + 40, { steps: 8 });
  await page.mouse.up();
  await map.getByTestId("address-map-confirm").click();
  await address.getByLabel("Улица", { exact: true }).fill("Рудаки");
  await address.getByLabel("Дом", { exact: true }).fill("15");
  await address.getByTestId("address-next").click();
  const coordinates = await address.locator(".address-tools small").innerText();
  expect(coordinates).not.toBe("38.56000, 68.77000");
  await address.getByRole("button", { name: "Доставить сюда", exact: true }).click();
  const product = page.locator(".product-card").first();
  await product.locator("h3 a").click();
  const sheet = page.getByRole("dialog");
  await sheet.getByRole("button", { name: "В корзину", exact: true }).click();
  const handle = sheet.locator('[class*="handle"]').last();
  const handleBox = (await handle.boundingBox())!;
  await page.mouse.move(handleBox.x + 20, handleBox.y + 10);
  await page.mouse.down();
  await page.mouse.move(handleBox.x + 20, handleBox.y + 100, { steps: 8 });
  await page.mouse.up();
  await expect(sheet).toHaveCount(0);
  await page.reload();
  await expect(page.locator(".header-location--mobile")).toContainText("Рудаки, 15");
  await page.goto("/checkout");
  await expect(page.getByLabel("Улица", { exact: true })).toHaveValue("Рудаки");
  await expect(page.locator(".address-tools small")).toHaveText(coordinates);
});

