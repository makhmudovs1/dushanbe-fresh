    await expect(dialog).toBeVisible();
    await dialog.getByLabel(text("Телефон", "Телефон"), { exact: true }).fill(phone);
    await dialog.getByRole("button", { name: text("Получить код", "Гирифтани рамз"), exact: true }).click();
