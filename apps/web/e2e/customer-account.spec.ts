    await dialog.getByRole("button", { name: text("Подтвердить номер", "Тасдиқи рақам"), exact: true }).click();
    await expect(dialog.getByRole("alert")).toBeVisible();
    await codeInput.fill(captured.code);
    await dialog.getByRole("button", { name: text("Подтвердить номер", "Тасдиқи рақам"), exact: true }).click();
    await expect(dialog).toHaveCount(0);
    await page.getByLabel(text("Имя", "Ном"), { exact: true }).fill(`Browser customer ${index}`);
    await page.getByLabel(text("Частный дом", "Ҳавлии шахсӣ"), { exact: true }).check();
    await expect(page.getByLabel(text("Квартира", "Ҳуҷра"), { exact: true })).toHaveCount(1); // Only the housing selector remains.
    await page.getByLabel(text("Улица", "Кӯча"), { exact: true }).fill("Рудаки");
    await page.getByLabel(text("Дом", "Хона"), { exact: true }).fill("15");
    await page.getByLabel(text("Комментарий / ориентир", "Эзоҳ / нишона"), { exact: true }).fill("Тестовый ориентир");
    await page.getByLabel(text("Сохранить адрес в личном кабинете", "Сабти суроға дар ҳисоби шахсӣ")).check();
    await page.locator('input[name="delivery-slot"][value="account-browser-20261021"]').check();
    await expect(page.locator(".checkout-lines li")).toHaveCount(1);
    await page.getByLabel(text("Я проверил товары, стоимость и время доставки", "Маҳсулот, нарх ва вақти расониданро санҷидам")).check();
    await page.reload();
    await expect(page.getByLabel(text("Улица", "Кӯча"), { exact: true })).toHaveValue("Рудаки");
    await expect(page.getByLabel(text("Частный дом", "Ҳавлии шахсӣ"), { exact: true })).toBeChecked();
    // Save preference is intentionally not persisted; opt in again after reload.
    await page.getByLabel(text("Сохранить адрес в личном кабинете", "Сабти суроға дар ҳисоби шахсӣ")).check();
    await page.getByLabel(text("Я проверил товары, стоимость и время доставки", "Маҳсулот, нарх ва вақти расониданро санҷидам")).check();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: info.outputPath(`checkout-${viewport.locale}-${viewport.width}.png`), fullPage: true });
