    await page.getByLabel(text("Улица", "Кӯча"), { exact: true }).fill("Сомони");
    await page.getByLabel(text("Дом", "Хона"), { exact: true }).fill("7");
    await page.locator('.address-editor input[autocomplete="address-line1"]').focus();
