export function productDescription(product: DescriptionSource, locale: "ru" | "tg"): string {
  const saved = locale === "tg" ? product.descriptionTj : product.description;
  if (saved?.trim()) return saved.trim();
  const fallback = descriptions[product.slug ?? ""] ?? ["Продукт для повседневного домашнего меню.", "Маҳсулот барои таомҳои ҳаррӯзаи хонагӣ."];
  return fallback[locale === "tg" ? 1 : 0];
}

export function missingProductDescriptions(product: DescriptionSource) {
  return {
    ...(!product.description?.trim() ? { description: productDescription(product, "ru") } : {}),
    ...(!product.descriptionTj?.trim() ? { descriptionTj: productDescription(product, "tg") } : {})
  };
}
