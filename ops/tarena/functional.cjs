const fs=require('node:fs'),path=require('node:path'),{spawnSync}=require('node:child_process');
const {chromium,webkit,firefox,expect}=require(require.resolve('@playwright/test',{paths:[path.resolve('apps/web')]}));
const readiness=process.env.TARENA_READINESS==='1';
const rehearsal=process.env.TARENA_REHEARSAL==='1';
const base=readiness?'https://localhost:8448':rehearsal?'https://localhost:8444':'https://localhost:8443';
const engine=['webkit','firefox'].includes(process.env.TARENA_BROWSER)?process.env.TARENA_BROWSER:'chromium';
const width=['375','390','430'].includes(process.env.TARENA_MOBILE_WIDTH)?Number(process.env.TARENA_MOBILE_WIDTH):engine==='webkit'?390:1440;
const directory=path.resolve(`apps/web/test-results/${readiness?'tarena-readiness':rehearsal?'tarena-rehearsal':'tarena'}-${engine}-${width}`);
let stage='startup',browser;
async function main(){
 const privatePath=readiness?'df-tarena-readiness-20261031':rehearsal?'df-tarena-rehearsal-20261029':'df-tarena-pilot';
 const read=spawnSync('ssh',['-F','ops/tarena/ssh_config','-o','BatchMode=yes','tarena-test',`cat "$HOME/${privatePath}/credentials.json"`],{encoding:'utf8',timeout:15000});
 if(read.status!==0)throw Error('private credentials unavailable');
 const credentials=JSON.parse(read.stdout);
 fs.mkdirSync(directory,{recursive:true});
 browser=await (engine==='webkit'?webkit:engine==='firefox'?firefox:chromium).launch(engine==='chromium'?{channel:'chrome'}:{});
 const context=await browser.newContext({baseURL:base,ignoreHTTPSErrors:true,viewport:{width,height:900},isMobile:engine!=='firefox'&&width<768,hasTouch:width<768});
 const products=await (await context.request.get('/api/v1/products')).json();
 if(!Array.isArray(products)||products.length!==100||products.some(p=>!/^tarena-product-\d+$/.test(p.id)))throw Error('Not the synthetic staging');
 const page=await context.newPage();
 const visit=async href=>{await page.waitForLoadState('networkidle');await page.goto(href);await page.waitForLoadState('networkidle');};
 stage='catalog/cart';
 await visit('/catalog?category=vegetables');
 const first=page.locator('.product-card:visible').filter({has:page.locator('a[href="/products/tarena-product-1"]')});
 const second=page.locator('.product-card:visible').filter({has:page.locator('a[href="/products/tarena-product-2"]')});
 await first.locator('.product-card__action').click();
 await page.locator('.address-invitation .secondary-link').click();
 await first.locator('.quantity-stepper button').last().click();
 await second.locator('.product-card__action').click();
 for(let i=0;i<3;i++)await second.locator('.quantity-stepper button').last().click();
 await expect(first.locator('output')).toHaveAttribute('aria-label','1 кг');
 await expect(second.locator('output')).toHaveAttribute('aria-label','2 кг');
 await visit('/cart');await expect(page.locator('.cart-item')).toHaveCount(2);
 await page.reload();await expect(page.locator('.cart-item')).toHaveCount(2);
 await page.waitForLoadState('networkidle');
 await page.screenshot({path:path.join(directory,'cart.png')});
 stage='product route';await visit('/products/tarena-product-1');
 await expect(page.getByRole('heading',{level:1,name:/картофель белый/})).toBeVisible();
 if(width<768)await expect.poll(async()=>{const r=await page.getByRole('dialog').locator('footer').boundingBox();return r?r.y+r.height:Infinity;}).toBeLessThanOrEqual(901);
 await page.screenshot({path:path.join(directory,'product.png')});
 stage='guest checkout';
 await visit('/checkout');
 await page.getByLabel('Имя',{exact:true}).fill('Pilot synthetic');
 await page.getByLabel('Телефон',{exact:true}).fill('+992900000000');
 await page.locator('.housing-toggle').getByText('Частный дом',{exact:true}).click();
 await page.getByLabel('Улица',{exact:true}).fill('Синтетическая улица');
 await page.getByLabel('Дом',{exact:true}).fill('99');
 await page.locator('input[name="delivery-slot"]:enabled').first().check();
 const accept=page.getByLabel('Я проверил товары, стоимость и время доставки');
 await expect(accept).toBeEnabled({timeout:20000});await accept.check();
 await page.getByRole('button',{name:'Подтвердить заказ',exact:true}).click();
 await expect(page).toHaveURL(/\/orders\/DF-.+\/success$/,{timeout:20000});
 const number=new URL(page.url()).pathname.split('/')[2];
 stage='staff auth';
 const login=async role=>{
  const r=await context.request.post('/api/v1/auth/admin/login',{headers:{Origin:base},data:credentials[role]});
  if(r.status()!==200)throw Error('staff login failed');
  const body=await r.json();if(!body.accessToken)throw Error('no staff session');return body.accessToken;
 };
 let token=await login('admin');
 const api=async(route,method='GET',body)=>{
  const r=await context.request.fetch('/api/v1'+route,{method,headers:{Origin:base,Authorization:'Bearer '+token},...(body?{data:body}:{})});
  if(!r.ok())throw Error('Operation failed '+r.status()+' '+route);
  return r.status()===204?null:r.json();
 };
 let uploadedImage=false;
 if((rehearsal||readiness)&&engine==='chromium'){
  stage='real upload parser/decoder';
  const upload=await context.request.post('/api/v1/admin/product-images',{headers:{Origin:base,Authorization:'Bearer '+token},multipart:{file:{name:'synthetic.webp',mimeType:'image/webp',buffer:fs.readFileSync('apps/web/public/storefront/v2/vegetables.webp')}}});
  if(upload.status()!==201)throw Error('synthetic upload failed');
  const photo=await upload.json();if(!/^\/api\/v1\/media\/[a-f0-9-]{36}\.webp$/.test(photo.image))throw Error('invalid media key');
  const changed=await api('/admin/products/tarena-product-1','PATCH',{image:photo.image});
  if(changed.image!==photo.image)throw Error('Uploaded image was not attached');uploadedImage=true;
 }
 const all=await api('/admin/orders');
 const order=all.find(o=>o.orderNumber===number);
 if(!order||order.items.length!==2||order.totalEstimated!=='25.00')throw Error('order variety/price mismatch');
 await visit('/admin/orders');
 await expect(page.getByRole('heading',{name:'Заказы',exact:true})).toBeVisible();
 await expect(page.getByText(number,{exact:true})).toBeVisible();
 await page.reload();await expect(page.getByText(number,{exact:true})).toBeVisible();
 await page.screenshot({path:path.join(directory,'admin-orders.png')});
 stage='picker actual weights';
 token=await login('picker');
 const wave=await api('/admin/delivery-waves/'+order.deliveryWaveId);
 if(wave.pickingList.length!==2||new Set(wave.pickingList.map(x=>x.productId)).size!==2)throw Error('wave merged varieties');
 await api('/admin/delivery-waves/'+wave.id+'/status','PATCH',{status:'picking'});
 for(const item of wave.pickingList)await api(`/admin/delivery-waves/${wave.id}/items/${item.id}`,'PATCH',{purchasedQuantity:readiness?'20':'3',purchaseUnitPrice:'5'});
 for(const item of order.items)await api(`/admin/orders/${order.id}/items/${item.id}`,'PATCH',{status:'picked',finalQuantity:item.productId==='tarena-product-1'?'0.9':'2.1'});
 const packed=await api('/admin/orders/'+order.id);
 if(packed.totalFinal!=='25.20')throw Error('actual-weight total mismatch');
 const forbidden=await context.request.get(base+'/api/v1/admin/settings',{headers:{Authorization:'Bearer '+token}});
 if(forbidden.status()!==403)throw Error('picker privilege mismatch');
 stage='courier and logout';token=await login('courier');
 const assigned=await api('/admin/delivery-waves');
 if(!assigned.some(x=>x.id===wave.id))throw Error('courier cannot see assigned wave');
 await context.request.post('/api/v1/auth/logout',{headers:{Origin:base}});
 const after=await context.request.get('/api/v1/me',{headers:{Authorization:'Bearer '+token}});
 if(after.status()!==401)throw Error('logout did not revoke session');
 const status=await (await context.request.get('/api/v1/customer-auth/status')).json();
 if(status.enabled||status.requiredForCheckout)throw Error('Unexpected SMS activation');
 stage='Tajik catalog';
 await context.addCookies([{name:'df-language',value:'tg',url:base}]);
 await visit('/catalog?category=vegetables');
 await expect(page.locator('.product-card h3').first()).toContainText('Маҳсулоти санҷишӣ 1');
 await page.screenshot({path:path.join(directory,'catalog-tg.png')});
 await context.close();
 console.log(JSON.stringify({engine,width,passed:true,syntheticOnly:true,catalogProducts:100,cartReload:true,guestCheckout:true,staffSessionReload:true,separateVarieties:true,finalGoodsTotal:'25.20',pickerPrivileges:true,courierAssignment:true,logout:true,tajikCatalog:true,smsEnabled:false,uploadedImage}));
}
main().catch(()=>{console.error(JSON.stringify({engine,passed:false,stage,sensitiveDetailsOmitted:true}));process.exitCode=1;}).finally(()=>browser?.close());
